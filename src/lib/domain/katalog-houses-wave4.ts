function row(r: Row, sortOrder: number): HouseSpec {
  const sucht = r.kind === "sucht" || r.kind === "dual";
  const alkohol = r.alk === undefined ? (sucht ? true : null) : r.alk;
  const drogen = r.drog === undefined ? (sucht ? true : null) : r.drog;
  const medikamente = r.med === undefined ? (sucht ? true : null) : r.med;
  const substances =
    r.kind === "psychosomatik"
      ? [...psycho]
      : r.kind === "dual"
        ? [...dualSub]
        : drogen === false
          ? [...suchtAlkMed]
          : [...suchtAll];
  return {
    id: r.id,
    name: r.name,
    shortName: r.short,
    city: r.city,
    plz: r.plz,
    street: r.street,
    stateCode: r.st,
    stateName: STATES[r.st] ?? r.st,
    traeger: r.traeger,
    traegerArt: r.art,
    phone: r.phone ?? NA,
    email: r.email ?? NA,
    website: r.web,
    indicationAreas: [r.kind],
    alkohol,
    drogen,
    medikamente,
    gluecksspiel: r.glueck ?? false,
    substitution: r.subst ?? false,
    substMittel: r.substM ?? (r.subst ? NA : sucht ? NA : "nicht angeboten"),
    substances,
    therapyForms: [...einzelGruppe],
    durationWeeksMin: r.dmin,
    durationWeeksMax: r.dmax,
    genderSetting: r.gender ?? "gemischt",
    setting: r.setting ?? "stationaer",
    ahb: r.ahb ?? r.kind === "psychosomatik",
    heilverfahren: r.hv ?? true,
    barrierefrei: r.bar ?? false,
    angehoerigenarbeit: true,
    kinderbetreuung: r.kinder ?? false,
    trauma: r.trauma ?? false,
    jungeErwachsene: r.jung ?? false,
    placesEstimate: r.places ?? (sucht ? 80 : 120),
    occupancyIndex: r.occ ?? 1.15,
    waitBaseDays: r.wait ?? (sucht ? 48 : 32),
    waitVarianceDays: sucht ? 14 : 10,
    sortOrder,
    speiseraum: true,
    besonderheit: sucht ? "werkstatt" : "garten",
    room: r.room ?? "unbekannt",
    wahl: "unbekannt",
    lage: r.lage,
    fokus: r.fokus,
    facts: r.facts.slice(0, 3),
  };
}

